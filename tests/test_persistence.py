"""Shared requirement #4: schema as migrations, the right indexes, isolated tenants (section 6, Backend box 1)."""
import pytest
from alembic import command
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError

from app.cli import DEMO_TENANTS, seed
from app.db.session import get_engine

REQUIRED_INDEXES = {
    "uq_images_tenant_id_sha256",
    "ix_images_tenant_id_status",
    "ix_images_tenant_id_subject_key",
    "ix_image_tags_tenant_id_tag",
    "uq_posts_tenant_id_slug",
    "uq_embeddings_tenant_id_owner_type_owner_id_model",
    "ix_embeddings_tenant_id_owner_type_model",
    "uq_suggestions_tenant_id_post_id_image_id_guard_version",
    "ix_suggestions_tenant_id_post_id_rank",
    "uq_reviews_suggestion_id",
    "ix_reviews_tenant_id_decision",
    "ix_jobs_tenant_id_status",
    "uq_job_items_job_id_item_id",
    "ix_job_items_status_next_run_at",
    "ix_ai_calls_tenant_id_created_at",
    "ix_ai_calls_job_id",
    "ix_ai_calls_entity_type_entity_id",
    "ix_alerts_tenant_id_created_at",
    "pk_idempotency_keys",
}


def test_models_and_migrations_are_in_sync(alembic_cfg):
    # Raises AutogenerateDiffsDetected if app/db/models.py drifted from the migrations.
    command.check(alembic_cfg)


def test_required_indexes_exist():
    with get_engine().connect() as conn:
        names = set(conn.scalars(text("SELECT indexname FROM pg_indexes WHERE schemaname = 'public'")))
    assert REQUIRED_INDEXES <= names, f"missing: {sorted(REQUIRED_INDEXES - names)}"


def test_pgvector_extension_installed():
    with get_engine().connect() as conn:
        assert conn.scalar(text("SELECT 1 FROM pg_extension WHERE extname = 'vector'")) == 1


def test_same_image_twice_in_one_tenant_is_rejected_but_allowed_across_tenants():
    insert = text("INSERT INTO images (tenant_id, sha256, file_path) VALUES (:t, :h, 'a.jpg')")
    with get_engine().begin() as conn:
        conn.execute(insert, {"t": "demo", "h": "a" * 64})
        conn.execute(insert, {"t": "other", "h": "a" * 64})
    with pytest.raises(IntegrityError), get_engine().begin() as conn:
        conn.execute(insert, {"t": "demo", "h": "a" * 64})


def test_invalid_status_is_rejected_by_check_constraint():
    with pytest.raises(IntegrityError), get_engine().begin() as conn:
        conn.execute(text("INSERT INTO images (tenant_id, sha256, file_path, status) "
                          "VALUES ('demo', :h, 'a.jpg', 'probably-fine')"), {"h": "b" * 64})


def test_seed_is_idempotent():
    seed()
    seed()
    with get_engine().connect() as conn:
        ids = set(conn.scalars(text("SELECT id FROM tenants")))
    assert ids == set(DEMO_TENANTS)


def test_migrations_downgrade_and_upgrade_cleanly(alembic_cfg):
    command.downgrade(alembic_cfg, "base")
    command.upgrade(alembic_cfg, "head")
    seed()  # restore tenants for any test that runs after this one
